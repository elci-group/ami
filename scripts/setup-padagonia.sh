#!/usr/bin/env bash
# Bootstraps a working local Padagonia configuration for Ami so the research
# database works instantly after a fresh clone/install, with no manual API
# key crafting. Idempotent: re-running it leaves an existing padagonia.toml
# and .env alone unless --force is passed.
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."

FORCE=0
if [[ "${1:-}" == "--force" ]]; then
    FORCE=1
fi

if [[ -f padagonia.toml && "$FORCE" -ne 1 ]]; then
    echo "padagonia.toml already exists; leaving it alone (use --force to regenerate)." >&2
    exit 0
fi

if ! command -v openssl >/dev/null 2>&1; then
    echo "error: openssl is required to generate a random API key" >&2
    exit 1
fi

API_KEY=$(openssl rand -hex 32)
LISTEN_ADDR="127.0.0.1:7373"
DATA_DIR=".padagonia-data"

cat > padagonia.toml <<EOF
# Generated by scripts/setup-padagonia.sh — local dev use only, do not commit.
[server]
listen_addr = "${LISTEN_ADDR}"
api_key = "${API_KEY}"
data_dir = "${DATA_DIR}/store.pad"

[storage]
data_dir = "${DATA_DIR}"
default_graph = "graph.pad"

[logging]
level = "info"
EOF

cat > .env <<EOF
# Generated by scripts/setup-padagonia.sh — local dev use only, do not commit.
export PADAGONIA_URL="http://${LISTEN_ADDR}"
export PADAGONIA_API_KEY="${API_KEY}"
EOF

mkdir -p "${DATA_DIR}"
chmod 600 padagonia.toml .env

echo "Wrote padagonia.toml and .env with a matching generated API key."
echo
echo "Next steps:"
echo "  1. Start the local Padagonia server (in this directory):"
echo "       padagonia server"
echo "  2. In another shell, load the matching client config and run ami:"
echo "       source .env"
echo "       ami analyze"
